export const SPECIAL_THEME_CHOICES = {
  SURPRISE: 'surprise',
  NONE: 'none',
} as const;

export function getThemeById(id?: string | null): CreativeTheme | undefined {
  if (!id || id === 'none' || id === 'surprise') return undefined;
  return CREATIVE_THEMES.find((t) => t.id === id);
}

export function getRandomTheme(): CreativeTheme {
  const randomIndex = Math.floor(Math.random() * CREATIVE_THEMES.length);
  return CREATIVE_THEMES[randomIndex];
}

export const LAST_THEME_STORAGE_KEY = 'create_again_last_theme';

export const THEMES = CREATIVE_THEMES;

export function getLastChosenThemeId(): string | null {
  try {
    return localStorage.getItem(LAST_THEME_STORAGE_KEY);
  } catch {
    return null;
  }
}

export function saveLastChosenThemeId(themeId: string): void {
  try {
    if (themeId && themeId !== 'none' && themeId !== 'surprise') {
      localStorage.setItem(LAST_THEME_STORAGE_KEY, themeId);
    }
  } catch {
    // Ignore storage write issues
  }
}
