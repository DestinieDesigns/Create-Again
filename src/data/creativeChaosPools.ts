export function getChaosPoolForTheme(themeId?: string | null): ThemedChaosPool {
  if (!themeId || themeId === 'none' || themeId === 'surprise') {
    return GENERAL_CHAOS_POOL;
  }
  const themed = THEMED_CHAOS_POOLS[themeId];
  if (!themed) return GENERAL_CHAOS_POOL;

  // Mix 70% themed elements with 30% general pool for delightful variety
  return {
    characters: [...themed.characters, ...GENERAL_CHAOS_POOL.characters.slice(0, 3)],
    features: [...themed.features, ...GENERAL_CHAOS_POOL.features.slice(0, 3)],
    settings: [...themed.settings, ...GENERAL_CHAOS_POOL.settings.slice(0, 3)],
    rules: [...themed.rules, ...GENERAL_CHAOS_POOL.rules.slice(0, 3)],
  };
}
