/**
 * Registry Lookup Helpers
 */
export function getAssetRecordById(id: string): ChibiAssetRecord | undefined {
  return chibiAssetManifest.find((a) => a.id === id);
}

export function getAssetsByCategory(category: string): ChibiAssetRecord[] {
  return chibiAssetManifest.filter((a) => a.category === category);
}

export function getAssetsByStatus(status: ChibiAssetRecord['status']): ChibiAssetRecord[] {
  return chibiAssetManifest.filter((a) => a.status === status);
}

export function getMissingAssets(): ChibiAssetRecord[] {
  return chibiAssetManifest.filter((a) => a.status === 'missing');
}

export function getAvailableAssets(): ChibiAssetRecord[] {
  return chibiAssetManifest.filter((a) => a.status === 'available');
}
